import crypto from 'crypto';
import { getRedis, isKvConfigured, STATE_KEY } from '@/lib/kv';

const BLACKLIST_FIELD = 'tp_blacklist';

// Same secret convention as lib/accounts.ts: ACCOUNTS_SECRET is the proper key,
// SITE_PASSWORD is a fallback so this works without new env setup. Whichever one
// is used, changing it invalidates every unsubscribe link already sent out — a
// stale link should just fail closed, not silently unsubscribe the wrong thing.
function secret(): string | null {
  return process.env.ACCOUNTS_SECRET || process.env.SITE_PASSWORD || null;
}

/**
 * A per-recipient token that proves "this link was generated by us for this
 * address" without needing a database lookup — anyone can see the email address
 * in the URL, but only someone holding the secret can produce a token that
 * verifies for it, so the endpoint can't be used to blacklist arbitrary
 * addresses on someone else's behalf.
 */
export function unsubscribeToken(email: string): string | null {
  const key = secret();
  if (!key) return null;
  return crypto.createHmac('sha256', key).update(email.trim().toLowerCase()).digest('hex').slice(0, 32);
}

export function verifyUnsubscribeToken(email: string, token: string): boolean {
  const expected = unsubscribeToken(email);
  if (!expected || !token) return false;
  const a = Buffer.from(expected);
  const b = Buffer.from(token);
  if (a.length !== b.length) return false;
  return crypto.timingSafeEqual(a, b);
}

function buildUrl(baseUrl: string, path: string, email: string): string | null {
  const token = unsubscribeToken(email);
  if (!token) return null;
  const url = new URL(path, baseUrl);
  url.searchParams.set('email', email);
  url.searchParams.set('token', token);
  return url.toString();
}

/** Human-facing landing page (app/unsubscribe/page.tsx) — the link that goes in the email body. */
export function buildUnsubscribeUrl(baseUrl: string, email: string): string | null {
  return buildUrl(baseUrl, '/unsubscribe', email);
}

/** Machine-facing endpoint (app/api/unsubscribe/route.ts) — what List-Unsubscribe points at, so
 *  Gmail/Yahoo/Outlook's built-in one-click "Unsubscribe" button (RFC 8058) can POST to it directly. */
export function buildUnsubscribeApiUrl(baseUrl: string, email: string): string | null {
  return buildUrl(baseUrl, '/api/unsubscribe', email);
}

async function readBlacklist(): Promise<string[]> {
  if (!isKvConfigured()) return [];
  const raw = await getRedis().hget<unknown>(STATE_KEY, BLACKLIST_FIELD);
  if (typeof raw === 'string') {
    try { return JSON.parse(raw); } catch { return []; }
  }
  return Array.isArray(raw) ? (raw as string[]) : [];
}

/**
 * Adds an address to the shared Do Not Contact list directly in Redis. The
 * unsubscribe page has no browser session to push the change through
 * syncStorage/localStorage the way the dashboard does — this writes straight to
 * the same settings field the dashboard reads on load, so it picks the change up
 * next time it syncs.
 */
export async function addToBlacklistServerSide(email: string): Promise<void> {
  if (!isKvConfigured()) return;
  const list = await readBlacklist();

  const lower = email.trim().toLowerCase();
  if (!list.some(e => String(e).toLowerCase() === lower)) {
    list.push(lower);
    await getRedis().hset(STATE_KEY, { [BLACKLIST_FIELD]: JSON.stringify(list) });
  }
}

/**
 * The authoritative Do Not Contact list, read straight from Redis rather than
 * trusting whatever a client posts — a stale dashboard tab only syncs this on
 * load, so anything unsubscribed since then would otherwise still get mailed.
 * Every send path (manual sends and the auto-follow-up cron) unions this with
 * whatever blacklist the caller passed, so an opt-out is honored the moment
 * it's recorded rather than on the client's next sync.
 */
export async function getBlacklist(): Promise<Set<string>> {
  const list = await readBlacklist();
  return new Set(list.map(e => String(e).trim().toLowerCase()));
}
